/**
 * «Наследство»: первый день в новой компании. Топология и размеры заморожены (configOnly),
 * чинить можно только настройки (knobs) в инспекторе. Алерты показывают лишь симптомы.
 */

function n(
  id: string,
  type: BlockType,
  label: string,
  instances = 1,
  size: NodeSize = 'S',
  extra: Partial<SimNodeConfig> = {},
  knobs?: Knobs,
): SimNodeConfig {
  return { id, type, label, instances, size, ...extra, ...(knobs ? { knobs } : {}) }
}

/** Чисто информационный алерт (без реального эффекта). */
function info(at: number, target: string, message: string): ScenarioEvent {
  return { at, kind: 'slow', target, value: 1, duration: 1, message }
}

