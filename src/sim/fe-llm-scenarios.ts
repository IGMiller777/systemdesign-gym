import type { Scenario, ScenarioEvent, SimNodeConfig, NodeSize, Knobs } from './types'
import type { BlockType } from '../tasks/types'

/**
 * Дежурства модулей «Фронтенд-архитектура» и «LLM-системы»:
 * SSR под рекламой, шторм переподключений, отказ LLM-провайдера, зациклившийся агент, переиндексация.
 */

function n(
  id: string,
  type: BlockType,
  label: string,
  instances = 1,
  size: NodeSize = 'S',
  extra: Partial<SimNodeConfig> = {},
  knobs?: Knobs,
): SimNodeConfig {
  return { id, type, label, instances, size, ...extra, ...(knobs ? { knobs } : {}) }
}

/** Чисто информационный алерт (без реального эффекта). */
function info(at: number, target: string, message: string): ScenarioEvent {
  return { at, kind: 'slow', target, value: 1, duration: 1, message }
}

