import { getScenario } from './scenarios'
import type { Scenario } from './types'

/** Hardcore variant: same incident, but the obvious tool is banned for an in-world reason. */
function hard(baseId: string, patch: Partial<Scenario> & Pick<Scenario, 'bannedBlocks' | 'briefing' | 'debrief'>): Scenario {
  const base = getScenario(baseId)!
  return { ...base, ...patch, id: `${baseId}-hc`, title: `${base.title} · хардкор`, hardOf: baseId }
}

