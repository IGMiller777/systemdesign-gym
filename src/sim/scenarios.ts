import type { Scenario, ScenarioEvent, SimNodeConfig, NodeSize } from './types'
import type { BlockType } from '../tasks/types'

function n(
  id: string,
  type: BlockType,
  label: string,
  instances = 1,
  size: NodeSize = 'S',
  extra: Partial<SimNodeConfig> = {},
): SimNodeConfig {
  return { id, type, label, instances, size, ...extra }
}

/** Чисто информационный алерт (без реального эффекта: slow ×1 на 1 тик). */
function info(at: number, target: string, message: string): ScenarioEvent {
  return { at, kind: 'slow', target, value: 1, duration: 1, message }
}

